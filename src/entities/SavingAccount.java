package entities;


import exceptions.InsufficientBalanceException;
import java.time.LocalDateTime;
import static entities.TransactionType.DEPOSIT;
import static entities.TransactionType.WITHDRAW;

/*
 - Savings account.
 - Generates a yield on every deposit and has daily limits for both
 - deposits and withdrawals.
 */
public class SavingAccount extends Account{
    private final double yieldRate; // Rate applied to each deposit to calculate its yield (0.1 = 10%)

    // Maximum number of deposits and withdrawals allowed per day
    private static final int DEPOSIT_LIMIT = 3;
    private static final int WITHDRAW_LIMIT = 2;

    /*
     - Creates a savings account. The data validation is done by the Account constructor.
     - @param accountNum    account number
     - @param holderName    holder name
     - @param holderCpf     holder CPF
     - @param holderAge     holder age
     - @param holderBalance initial balance
     */
    public SavingAccount(int accountNum, String holderName, String holderCpf, int holderAge, double holderBalance) {
        super(accountNum, holderName, holderCpf, holderAge, holderBalance);
        this.yieldRate = 0.1;
    }

    // Returns the rate applied to each deposit to calculate its yield.
    public double getYieldRate() {
        return this.yieldRate;
    }

    /*
     - Checks the daily deposit limit before a deposit is made.
     - @throws IllegalStateException if the daily deposit limit was already reached
     */
    @Override
    protected void validateLimitDeposit() {
        if(countToday(DEPOSIT) >= DEPOSIT_LIMIT){
            throw new IllegalStateException("[ERRO]: Limite diário de depósitos atingido.");
        }
    }

    /*
     - Calculates the yield of a deposit by applying the yield rate to its value.
     - @param value the deposited amount
     - @return the yield generated by that amount
     */
    @Override
    public double calculateYield(double value) {
        return value * getYieldRate();
    }

    /*
     -Withdraws the given value from the account.
     - Validates, in this order, the value, the daily withdraw limit and the
     - available balance. Then subtracts the value from the balance and registers a WITHDRAW transaction.
     - @param value the amount to withdraw
     - @throws exceptions.InvalidValueException  if the value is not finite or not greater than zero
     - @throws IllegalStateException             if the daily withdraw limit was already reached
     - @throws InsufficientBalanceException      if the value is greater than the current balance
     */
    @Override
    public void moneyWithdraw(double value) {
        validateValue(value);
        if(countToday(WITHDRAW) >= WITHDRAW_LIMIT){
            throw new IllegalStateException("[ERRO]: Limite diário de saques atingido   .\n");
        }
        if(value > getAccountBalance()){
            throw new InsufficientBalanceException();
        }

        setBalance(getAccountBalance() - value);
        getTransaction().add(new Transaction(WITHDRAW, LocalDateTime.now(), value));
    }
}
