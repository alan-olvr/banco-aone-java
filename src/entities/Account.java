package entities;

import java.util.List;
import java.util.ArrayList;

import exceptions.InvalidDataAccountException;
import exceptions.InvalidValueException;

import java.time.LocalDateTime;
import java.time.LocalDate;
import static entities.TransactionType.DEPOSIT;

/*
 - Base class for bank accounts.
 - Holds the holder data, the balance and the transaction history, and
 - implements the operations shared by every account type. Each subclass
 - defines its own withdrawal rules and may customize yield and deposit limits.
 */

public abstract class Account {
    private final int accountNum;
    private final String holderName, holderCpf;
    private final int holderAge;
    private double accountBalance;
    private final List<Transaction> transactions = new ArrayList<>();

    //Business rules used to validate the account data
    public static final int MIN_AGE = 16; //minimum age of the holder
    public static final int CPF_LENGTH = 11; //number of digits of the CPF
    public static final int ACCOUNT_NUM_MIN = 100_000; //smallest valid account number (6 digits)
    public static final int ACCOUNT_NUM_MAX = 999_999; //largest valid account number (6 digits)

    /*
     - Creates an account after validating every piece of data received.
     - Nothing is assigned if any validation fails.
     - @param accountNum     account number, between ACCOUNT_NUM_MIN and ACCOUNT_NUM_MAX
     - @param holderName     holder name, not blank and without digits
     - @param holderCpf      holder CPF, exactly CPF_LENGTH numeric digits
     - @param holderAge      holder age, at least MIN_AGE
     - @param accountBalance initial balance, finite and greater than or equal to zero
     - @throws InvalidDataAccountException if any of the data is invalid
     */
    public Account(int accountNum, String holderName, String holderCpf, int holderAge, double accountBalance) {
        require(accountNum >= ACCOUNT_NUM_MIN && accountNum <= ACCOUNT_NUM_MAX, "[ERRO]: Número da conta inválido. Deve ter 6 dígitos.");
        require(holderName != null && !holderName.isBlank() && holderName.chars().noneMatch(Character::isDigit), "[ERRO]: Nome inválido. Não pode estar em branco nem conter dígitos.");
        require(holderCpf != null && holderCpf.matches("\\d{" + CPF_LENGTH + "}"), "[ERRO]: CPF inválido. Deve conter exatamente 11 dígitos numéricos.");
        require(holderAge >= MIN_AGE, "[ERRO]: Idade inválida. A idade mínima é: " + MIN_AGE + " anos.");
        require(Double.isFinite(accountBalance) && accountBalance >= 0, "[ERRO]: Saldo inicial inválido.");

        this.accountNum = accountNum;
        this.holderName = holderName;
        this.holderCpf = holderCpf;
        this.holderAge = holderAge;
        this.accountBalance = accountBalance;
    }

    // ----- Getters and setters -----

    // Returns the account number.
    public int getAccountNum() {
        return this.accountNum;
    }

    //Returns the holder name.
    public String getHolderName() {
        return this.holderName;
    }

    //Returns the holder cpf.
    public String getHolderCpf() {
        return this.holderCpf;
    }

    //Returns the holder age.
    public int getHolderAge() {
        return this.holderAge;
    }

    //Returns the current account balance.
    public double getAccountBalance() {
        return this.accountBalance;
    }

    //Returns the list with every transaction registered in the account.
    public List<Transaction> getTransaction() {
        return this.transactions;
    }

    /*
     - Replaces the account balance. Only available to subclasses,
     - which use it to apply the result of a withdrawal.
     - @param balance the new balance
     */
    protected void setBalance(double balance) {
        this.accountBalance = balance;
    }

    //----- Concrete methods -----

    /*
     - Deposits the given value into the account.
     - Validates the value and the deposit limit, adds the value plus its
     - yield to the balance and registers a DEPOSIT transaction with the deposited value.
     - @param value the amount to deposit
     - @throws InvalidValueException if the value is not finite or not greater than zero
     */
    public void deposit(double value) {
       validateValue(value);
       validateLimitDeposit();
       accountBalance += value + calculateYield(value);
       transactions.add(new Transaction(DEPOSIT, LocalDateTime.now(), value));
    }

    /*
     - Calculates the yield generated by a deposit of the given value.
     - The base implementation has no yield; subclasses override it to apply their own rate.
     - @param value the deposited amount
     - @return the yield for that amount (zero in this class)
     */
    public double calculateYield(double value){
        return 0;
    }

    /*
     - Calculates the accumulated yield of the account, summing the yield
     - of every deposit registered in the transaction history.
     - @return the total accumulated yield
     */
    public double totalYield() {
        double total = 0;
        for(Transaction t: getTransaction()) {
            if(t.getType() == DEPOSIT){
                total += calculateYield(t.getValue());
            }
        }
        return total;
    }

    /*
     - Prints every transaction registered in the account (deposits and withdrawals).
     - @throws IllegalArgumentException if there are no transactions yet
     */
    public void consultExtract(){
        if(!getTransaction().isEmpty()) {
            getTransaction().forEach(System.out::println);
        } else {
            throw new IllegalArgumentException("[AVISO]: Nenhuma movimentação registrada até o momento.");
        }
    }

    /*
     - Returns only the transactions of the given type (deposits or withdrawals).
     - @param type the transaction type used as filter
     - @return a new list with the transactions of that type
     - @throws IllegalArgumentException if there are no transactions yet
     */
    public List<Transaction> consultExtract(TransactionType type){
        if (!getTransaction().isEmpty()) {
            ArrayList<Transaction> transaction = new ArrayList<>();
            for (Transaction t : getTransaction()) {
                if (t.getType() == type) {
                    transaction.add(t);
                }
            }
            return transaction;
        } else {
            throw new IllegalArgumentException("[ERRO]: Nenhum " + type + " registrado.");
        }
    }

    /*
     - Checks a condition and throws when it is false. Used by the constructor
     - to validate each piece of account data in a single line.
     - @param condition the condition that must be true
     - @param message   the message of the exception thrown when the condition is false
     - @throws InvalidDataAccountException if the condition is false
     */
    private static void require(boolean condition, String message) {
        if(!condition) throw new InvalidDataAccountException(message);
    }

    /*
     - Hook called before every deposit. The base implementation has no limit;
     - subclasses override it to enforce their own deposit limit.
     */
    protected void validateLimitDeposit(){ }

    /*
     - Validates an amount used in an operation.
     - @param value the amount to validate
     - @throws InvalidValueException if the value is not finite or not greater than zero
     */
    protected void validateValue(double value){
        if(!Double.isFinite(value) || value <= 0) {
            throw new InvalidValueException();
        }
    }

    /*
     - Returns how many transactions of the given type were registered today,
     - according to the system date.
     - @param type the transaction type to count (DEPOSIT or WITHDRAW)
     - @return the number of transactions of that type made today
     */
    protected long countToday(TransactionType type){
        LocalDate today = LocalDate.now();
        long count = 0;
        for(Transaction t: transactions){
            if(t.getType() == type && t.getMoment().toLocalDate().equals(today)){
                count++;
            }
        }
        return count;
    }

    //----- Abstract method -----

    /*
     - Withdraws the given value from the account. Each account type defines
     - its own rules (such as the daily withdraw limit).
     - @param value the amount to withdraw
     */
    public abstract void moneyWithdraw(double value);

}
